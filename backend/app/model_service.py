from pathlib import Path
import numpy as np
from .audio_features import extract_mfcc, audio_stats

MODEL_PATH = Path(__file__).resolve().parents[1] / "models" / "model.tflite"

def _sigmoid(x: float) -> float:
    return float(1 / (1 + np.exp(-x)))

class DeepfakeAudioDetector:
    def __init__(self):
        self.mode = "demo-mfcc-heuristic"
        self.interpreter = None
        self.input_details = None
        self.output_details = None
        self._try_load_tflite()

    def _try_load_tflite(self):
        if not MODEL_PATH.exists():
            return
        try:
            try:
                import tensorflow as tf
                self.interpreter = tf.lite.Interpreter(model_path=str(MODEL_PATH))
            except Exception:
                from tflite_runtime.interpreter import Interpreter
                self.interpreter = Interpreter(model_path=str(MODEL_PATH))
            self.interpreter.allocate_tensors()
            self.input_details = self.interpreter.get_input_details()
            self.output_details = self.interpreter.get_output_details()
            self.mode = "tflite"
        except Exception:
            self.mode = "demo-mfcc-heuristic"

    def predict(self, audio_path: str | Path) -> dict:
        mfcc = extract_mfcc(audio_path)
        stats = audio_stats(audio_path)

        if self.interpreter:
            x = mfcc[np.newaxis, ..., np.newaxis].astype("float32")
            self.interpreter.set_tensor(self.input_details[0]["index"], x)
            self.interpreter.invoke()
            raw = self.interpreter.get_tensor(self.output_details[0]["index"]).ravel()[0]
            fake_prob = float(raw)
        else:
            smoothness = float(np.mean(np.abs(np.diff(mfcc, axis=1))))
            energy = stats["rms_mean"]
            zcr = stats["zcr_mean"]
            centroid = stats["spectral_centroid_mean"] / 5000.0
            score = (smoothness * 0.9) + (zcr * 3.5) + (centroid * 0.7) - (energy * 1.2)
            fake_prob = _sigmoid(score - 1.35)

        label = "FAKE" if fake_prob >= 0.5 else "REAL"
        confidence = fake_prob if label == "FAKE" else 1 - fake_prob
        risk = "High" if confidence >= 0.82 else "Medium" if confidence >= 0.62 else "Low"
        return {
            "label": label,
            "confidence": round(confidence * 100, 2),
            "fake_probability": round(fake_prob * 100, 2),
            "risk_level": risk,
            "model_mode": self.mode,
            "audio_features": stats,
            "explanation": (
                "Prediction is based on MFCC voice-pattern features and spectral statistics. "
                "For production, train the CNN and replace demo scoring with model.tflite."
                if self.mode != "tflite"
                else "Prediction generated by TensorFlow Lite model using MFCC input features."
            )
        }

detector = DeepfakeAudioDetector()
